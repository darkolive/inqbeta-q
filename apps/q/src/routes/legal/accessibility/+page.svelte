<h1 class="h2">Accessibility statement</h1>
<p class="text-sm text-surface-700-300">Last updated 1 October 2026.</p>

<p>
	Q is built to be calm, clear and usable by as many people as possible — including people who are
	neurodivergent, who use a screen reader, or who find a busy screen hard going.
</p>

<h2>What Q does</h2>
<ul>
	<li><strong>Read aloud</strong> in a recorded human voice, with each word lit as it is spoken. Click any
		word to hear from there.</li>
	<li><strong>Six languages</strong>: English, Welsh, French, German, Spanish and Simplified Chinese.</li>
	<li><strong>Light and dark</strong> themes, following your device unless you choose.</li>
	<li><strong>Reduced motion</strong> is respected: no autoplay, no fades, no gliding scroll.</li>
	<li><strong>Keyboard</strong>: everything can be reached and used without a mouse, with a skip link at the
		top of the home page.</li>
	<li><strong>Plain words</strong>, one idea at a time, and no timed steps.</li>
	<li>Text alternatives for pictures, and landmarks and headings for screen readers.</li>
</ul>

<h2>What we know is not yet right</h2>
<ul>
	<li>Q has not yet had an independent accessibility audit against WCAG 2.2 AA; that is planned.</li>
	<li>The legal pages are in English only for now.</li>
	<li>Some newer parts of the dashboard have not been checked with every screen reader.</li>
</ul>

<h2>Tell us about a barrier</h2>
<p>
	If something in Q gets in your way, please <a href="/contact">tell us</a> — what you were trying to do,
	and what you use (for example a screen reader or voice control). We read every message.
</p>
