<h1 class="h2">Privacy notice</h1>
<p class="text-sm text-surface-700-300">Last updated 1 October 2026.</p>

<p>
	Q is designed so that your records stay with you. This notice says, plainly, what that means and the
	few things that do pass through our servers.
</p>

<h2>Who we are</h2>
<p>
	Q is provided by <a href="https://darkolive.co.uk">Dark Olive CIC</a>, a community interest company
	registered in England and Wales. For the few things below, Dark Olive CIC is the data controller. You
	can reach us through the <a href="/contact">contact page</a>.
</p>

<h2>What Q does not collect</h2>
<ul>
	<li>No account and no password. You sign in with a passkey, which never leaves your device.</li>
	<li>No database of people. Your keys, your identity and your records are kept on your device, and in
		any cloud folder <em>you</em> choose to connect — encrypted before they leave your device.</li>
	<li>No cookies, no analytics, no advertising and no trackers.</li>
</ul>

<h2>What passes through our servers, and why</h2>
<ul>
	<li><strong>Stay in touch and Contact.</strong> If you give us your email address or send a message, it is
		emailed once to Dark Olive CIC's admin inbox so we can reply. It is not stored on Q's servers; it is
		kept in that inbox for as long as the conversation needs, and deleted on request.</li>
	<li><strong>Sign-in and notice emails.</strong> If you ask Q to email you (for example a sign-in link), the
		address is used to send that email. Q keeps the address only in a sealed form that you hold.</li>
	<li><strong>Google Drive, if you connect it.</strong> Q exchanges Google's sign-in codes for access through
		our server and keeps nothing; Q can only reach the files and folder it made in your Drive.</li>
	<li><strong>Calls.</strong> Calls go directly between devices. To find that direct route, your device asks
		a public STUN server (Cloudflare's or Google's), which sees your IP address and nothing else. Where a
		relay is set up and a network blocks direct calls, the call is relayed still encrypted, with short-lived
		credentials; the relay cannot read it.</li>
	<li><strong>Hosting logs.</strong> Like any website, our host records requests — the page asked for, the
		time and your IP address — to keep the service running and secure. These logs are kept briefly.</li>
</ul>

<h2>Who helps us</h2>
<ul>
	<li><a href="https://vercel.com">Vercel</a> hosts Q.</li>
	<li><a href="https://resend.com">Resend</a> sends Q's emails.</li>
	<li><a href="https://cloudflare.com">Cloudflare</a> and <a href="https://google.com">Google</a> help a call
		find a direct route (STUN), and Cloudflare relays calls that cannot connect directly.</li>
	<li>Google again, for your Drive, only if you connect it yourself.</li>
</ul>
<p>Some of these providers may process data outside the UK, under their own safeguards.</p>

<h2>Your rights</h2>
<p>
	Under UK data protection law you can ask to see, correct or delete what we hold about you, or object
	to how it is used. Most of what Q holds is already in your hands: <em>Leave no trace</em> clears
	everything Q kept in your browser. For anything else, <a href="/contact">contact us</a>. If you are
	unhappy with how we have handled your information, you can complain to the
	<a href="https://ico.org.uk">Information Commissioner's Office</a>.
</p>
